const TEST_LEAD_TYPE = "e2e-test";

function log(label, msg) {
  console.log(`[${label}] ${msg}`);
}
function ok(msg) {
  console.log(`  [OK]   ${msg}`);
}
function fail(msg) {
  console.error(`  [FAIL] ${msg}`);
}

async function createTestLead() {
  const email = `e2e-${Date.now()}-${Math.floor(Math.random() * 1e4)}@example.test`;
  const lead = await PlatformLead.create({
    name: "E2E Test Lead",
    email,
    phone: null,
    type: TEST_LEAD_TYPE,
  });
  return lead;
}

async function buildDelayWorkflow(name, nodes, edges) {
  const wf = await Workflow.create({
    name: `E2E ${name} ${ulid().slice(-6)}`,
    description: "auto-generated by sandbox/e2e-workflow-test.js",
    status: WORKFLOW_STATUS.DRAFT,
  });
  await wf.update({
    trigger_config: {
      type: TRIGGER_TYPE.STATIC_LIST,
      config: {
        recipient_filter: {
          sources: [
            {
              type: "platform_leads",
              filters: { programs: [{ types: [TEST_LEAD_TYPE] }] },
            },
          ],
        },
        batch_size: 100,
      },
    },
    settings: {},
    draft_definition: { nodes, edges },
  });
  return wf;
}

function delayNode(id, seconds) {
  return {
    id,
    type: NODE_TYPE.CONTROL_DELAY,
    config: { duration_value: seconds, duration_unit: DURATION_UNIT.SECONDS },
  };
}

function goalNode(id, name = "completed") {
  return { id, type: NODE_TYPE.CONTROL_GOAL, config: { goal_name: name } };
}

async function enrollOne(workflow, lead) {
  const entryNode = workflow.draft_definition.nodes[0];
  // Walk the published version, not the draft, for current_node_id pinning
  const version = await WorkflowVersion.findOne({
    where: { workflow_id: workflow.id, version: workflow.current_version },
  });
  const entryId = version.definition.nodes[0].id;

  const enrollment = await WorkflowEnrollment.create({
    workflow_id: workflow.id,
    workflow_version: workflow.current_version,
    lead_source_type: LEAD_SOURCE_TYPE.PLATFORM_LEADS,
    lead_source_id: String(lead.id),
    lead_email_snapshot: lead.email,
    lead_phone_snapshot: lead.phone,
    lead_name_snapshot: lead.name,
    status: ENROLLMENT_STATUS.ACTIVE,
    current_node_id: entryId,
    enrollment_source: ENROLLMENT_SOURCE.MANUAL,
    context: { test: true },
    next_scheduled_at: new Date(),
  });

  await enqueueAdvance({
    enrollmentId: enrollment.id,
    nodeId: entryId,
    attempt: 1,
    delayMs: 0,
  });

  return enrollment;
}

async function waitFor(predicate, { timeoutMs = 20_000, intervalMs = 500 } = {}) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    const result = await predicate();
    if (result) return result;
    await sleep(intervalMs);
  }
  return null;
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function cleanup({ workflows = [], leads = [] }) {
  for (const wf of workflows) {
    await WorkflowNodeRun.destroy({
      where: {},
      truncate: false,
      include: [
        {
          model: WorkflowEnrollment,
          where: { workflow_id: wf.id },
        },
      ],
    }).catch(() => {});
    // Simpler: delete by enrollment_ids
    const ids = await WorkflowEnrollment.findAll({
      where: { workflow_id: wf.id },
      attributes: ["id"],
      raw: true,
    });
    await WorkflowNodeRun.destroy({
      where: { enrollment_id: ids.map((r) => r.id) },
    }).catch(() => {});
    await WorkflowEnrollment.destroy({ where: { workflow_id: wf.id } });
    await WorkflowVersion.destroy({ where: { workflow_id: wf.id } });
    await Workflow.destroy({ where: { id: wf.id } });
  }
  for (const lead of leads) {
    await LeadConsent.destroy({
      where: {
        lead_source_type: LEAD_SOURCE_TYPE.PLATFORM_LEADS,
        lead_source_id: String(lead.id),
      },
    }).catch(() => {});
    await PlatformLead.destroy({ where: { id: lead.id } });
  }
}

