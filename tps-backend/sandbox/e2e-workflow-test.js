/**
 * End-to-end smoke test for the workflow engine.
 *
 * Prerequisites:
 *   1. Redis running (docker container or local)
 *   2. The worker process running in another terminal:
 *      node workers/workflowWorker.js
 *
 * Usage:
 *   node sandbox/e2e-workflow-test.js                 # runs happy-path
 *   node sandbox/e2e-workflow-test.js happy-path
 *   node sandbox/e2e-workflow-test.js opt-out
 *   node sandbox/e2e-workflow-test.js pause-resume
 *   node sandbox/e2e-workflow-test.js idempotency
 *   node sandbox/e2e-workflow-test.js all
 *
 * Tests use 3-second delays and `control.goal` terminals — no real emails
 * are sent. Email path is exercised in a separate script.
 */

