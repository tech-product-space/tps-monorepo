async function scenarioHappyPath() {
  log("happy-path", "creating test lead + workflow");
  const lead = await createTestLead();
  const wf = await buildDelayWorkflow(
    "happy-path",
    [
      delayNode("n1", 2),
      delayNode("n2", 2),
      goalNode("n3"),
    ],
    [
      { from: "n1", to: "n2" },
      { from: "n2", to: "n3" },
    ]
  );

  log("happy-path", "publishing");
  await publishWorkflow({ workflowId: wf.id, publishedBy: "e2e" });
  await wf.reload();

  log("happy-path", "enrolling lead and watching it advance");
  const enrollment = await enrollOne(wf, lead);

  const done = await waitFor(
    async () => {
      const e = await WorkflowEnrollment.findByPk(enrollment.id);
      return e.status === ENROLLMENT_STATUS.COMPLETED ? e : null;
    },
    { timeoutMs: 15_000 }
  );

  let passed = true;
  if (done) ok(`enrollment completed in ~${ageSec(done.enrolled_at, done.completed_at)}s`);
  else {
    fail("enrollment never reached completed status within 15s");
    passed = false;
  }

  const runs = await WorkflowNodeRun.findAll({
    where: { enrollment_id: enrollment.id },
    order: [["started_at", "ASC"]],
  });
  if (runs.length === 3) ok(`3 node_runs recorded`);
  else {
    fail(`expected 3 node_runs, got ${runs.length}`);
    passed = false;
  }
  for (const r of runs) {
    if (r.status !== "completed" && r.status !== "skipped") {
      fail(`node_run ${r.node_id} status=${r.status}`);
      passed = false;
    }
  }

  await cleanup({ workflows: [wf], leads: [lead] });
  return passed;
}

async function scenarioOptOut() {
  log("opt-out", "creating test lead + 4-node workflow (delay→delay→delay→goal)");
  const lead = await createTestLead();
  const wf = await buildDelayWorkflow(
    "opt-out",
    [
      delayNode("n1", 2),
      delayNode("n2", 3),
      delayNode("n3", 3),
      goalNode("n4"),
    ],
    [
      { from: "n1", to: "n2" },
      { from: "n2", to: "n3" },
      { from: "n3", to: "n4" },
    ]
  );
  await publishWorkflow({ workflowId: wf.id, publishedBy: "e2e" });
  await wf.reload();

  const enrollment = await enrollOne(wf, lead);

  // Wait until enrollment is past first node so opt-out hits while in flight
  await waitFor(
    async () => {
      const e = await WorkflowEnrollment.findByPk(enrollment.id);
      return e.current_node_id !== "n1" ? e : null;
    },
    { timeoutMs: 8_000 }
  );

  log("opt-out", "calling opt-out for the lead");
  const {
    optOut,
  } = require("../controllers/lead/leadConsent.controller");
  // Simulate the controller's behavior directly
  const {
    recordOptOut,
  } = require("../service/workflow/compliance/optOutGuard");
  await sequelize.transaction(async (tx) => {
    await recordOptOut({
      sourceType: LEAD_SOURCE_TYPE.PLATFORM_LEADS,
      sourceId: String(lead.id),
      channel: "email",
      reason: "e2e_test",
    });
    await WorkflowEnrollment.update(
      {
        status: ENROLLMENT_STATUS.CANCELLED,
        completed_at: new Date(),
        current_node_id: null,
        next_scheduled_at: null,
        error_reason: "opted_out_email",
      },
      {
        where: {
          lead_source_type: LEAD_SOURCE_TYPE.PLATFORM_LEADS,
          lead_source_id: String(lead.id),
          status: ENROLLMENT_STATUS.ACTIVE,
        },
        transaction: tx,
      }
    );
  });

  const cancelled = await waitFor(
    async () => {
      const e = await WorkflowEnrollment.findByPk(enrollment.id);
      return e.status === ENROLLMENT_STATUS.CANCELLED ? e : null;
    },
    { timeoutMs: 3_000 }
  );

  let passed = true;
  if (cancelled) ok(`enrollment cancelled with reason=${cancelled.error_reason}`);
  else {
    fail("enrollment not cancelled after opt-out");
    passed = false;
  }

  // Wait a bit longer to ensure no rogue advances happen after cancellation
  await sleep(6_000);
  const final = await WorkflowEnrollment.findByPk(enrollment.id);
  if (final.status === ENROLLMENT_STATUS.CANCELLED)
    ok(`enrollment stayed cancelled (no resurrection)`);
  else {
    fail(`enrollment status changed to ${final.status} after cancel`);
    passed = false;
  }

  await cleanup({ workflows: [wf], leads: [lead] });
  return passed;
}

async function scenarioPauseResume() {
  log("pause-resume", "creating workflow with long delay (10s) and pausing mid-flight");
  const lead = await createTestLead();
  const wf = await buildDelayWorkflow(
    "pause-resume",
    [delayNode("n1", 6), goalNode("n2")],
    [{ from: "n1", to: "n2" }]
  );
  await publishWorkflow({ workflowId: wf.id, publishedBy: "e2e" });
  await wf.reload();

  const enrollment = await enrollOne(wf, lead);

  await sleep(1_000); // let the delay job get queued
  log("pause-resume", "pausing workflow");
  await wf.update({ status: WORKFLOW_STATUS.PAUSED });

  // Wait past the delay window; enrollment should NOT complete because paused
  await sleep(8_000);

  let mid = await WorkflowEnrollment.findByPk(enrollment.id);
  let passed = true;
  if (mid.status === ENROLLMENT_STATUS.ACTIVE) {
    ok(`enrollment stayed active during pause (status=${mid.status})`);
  } else {
    fail(`enrollment became ${mid.status} during pause`);
    passed = false;
  }

  log("pause-resume", "resuming workflow");
  await wf.update({ status: WORKFLOW_STATUS.ACTIVE });

  log("pause-resume", "forcing reconcile to pick up the stuck enrollment");
  await reconcileOnce();

  const done = await waitFor(
    async () => {
      const e = await WorkflowEnrollment.findByPk(enrollment.id);
      return e.status === ENROLLMENT_STATUS.COMPLETED ? e : null;
    },
    { timeoutMs: 10_000 }
  );

  if (done) ok(`enrollment completed after resume + reconcile`);
  else {
    fail(`enrollment did not complete after resume`);
    passed = false;
  }

  await cleanup({ workflows: [wf], leads: [lead] });
  return passed;
}

async function scenarioIdempotency() {
  log("idempotency", "creating workflow, enrolling, and double-enqueuing");
  const lead = await createTestLead();
  const wf = await buildDelayWorkflow(
    "idempotency",
    [delayNode("n1", 2), goalNode("n2")],
    [{ from: "n1", to: "n2" }]
  );
  await publishWorkflow({ workflowId: wf.id, publishedBy: "e2e" });
  await wf.reload();

  const enrollment = await enrollOne(wf, lead);

  // Enqueue the SAME jobId twice — BullMQ should dedup at jobId level
  log("idempotency", "enqueuing the same advance jobId 5x");
  for (let i = 0; i < 5; i++) {
    await enqueueAdvance({
      enrollmentId: enrollment.id,
      nodeId: "n1",
      attempt: 1,
      delayMs: 0,
    });
  }

  const done = await waitFor(
    async () => {
      const e = await WorkflowEnrollment.findByPk(enrollment.id);
      return e.status === ENROLLMENT_STATUS.COMPLETED ? e : null;
    },
    { timeoutMs: 10_000 }
  );

  let passed = true;
  if (!done) {
    fail("enrollment never completed");
    passed = false;
  }

  const runs = await WorkflowNodeRun.findAll({
    where: { enrollment_id: enrollment.id, node_id: "n1" },
  });
  if (runs.length === 1)
    ok(`only 1 node_run exists for n1 despite 5 enqueues (idempotency holds)`);
  else {
    fail(`expected 1 node_run for n1, got ${runs.length}`);
    passed = false;
  }

  await cleanup({ workflows: [wf], leads: [lead] });
  return passed;
}

function ageSec(start, end) {
  return Math.round((new Date(end).getTime() - new Date(start).getTime()) / 1000);
}

// ===========================================================================
// Main
// ===========================================================================

const SCENARIOS = {
  "happy-path": scenarioHappyPath,
  "opt-out": scenarioOptOut,
  "pause-resume": scenarioPauseResume,
  idempotency: scenarioIdempotency,
};

(async () => {
  const arg = (process.argv[2] || "happy-path").toLowerCase();
  const run =
    arg === "all" ? Object.entries(SCENARIOS) : [[arg, SCENARIOS[arg]]];

  if (!run[0][1]) {
    console.error(`unknown scenario: ${arg}`);
    console.error(`available: ${Object.keys(SCENARIOS).join(", ")}, all`);
    process.exit(2);
  }

  try {
    await sequelize.authenticate();
    console.log("=".repeat(60));
    console.log("workflow E2E smoke test");
    console.log("requires worker running:  node workers/workflowWorker.js");
    console.log("=".repeat(60));

    const results = [];
    for (const [name, fn] of run) {
      console.log(`\n--- scenario: ${name} ---`);
      const t0 = Date.now();
      let passed = false;
      try {
        passed = await fn();
      } catch (err) {
        fail(`scenario threw: ${err.message}`);
        console.error(err.stack);
      }
      results.push({ name, passed, ms: Date.now() - t0 });
    }

    console.log("\n" + "=".repeat(60));
    console.log("summary");
    console.log("=".repeat(60));
    for (const r of results) {
      console.log(
        `  ${r.passed ? "[PASS]" : "[FAIL]"}  ${r.name.padEnd(15)} ${r.ms}ms`
      );
    }
    const allPassed = results.every((r) => r.passed);

    // Close all connections
    await workflowAdvanceQueue.close();
    await workflowBulkEnrollQueue.close();
    try {
      await getSharedRedis().quit();
    } catch (e) {}
    await sequelize.close();

    process.exit(allPassed ? 0 : 1);
  } catch (err) {
    console.error("test runner failed:", err);
    process.exit(1);
  }
})();
